/** Fresh objects let callers shuffle tasks without damaging the authored bank. */
function withPassage(
  passage: ReadingPassage,
  question: Question,
): ReadingQuestion {
  return {
    ...question,
    choices: [...question.choices],
    passage: {
      title: passage.title,
      text: passage.text,
      genre: passage.genre,
      author: passage.author,
    },
  };
}

export const readingQuestions: ReadingQuestion[] = readingPassages.flatMap(
  (passage) =>
    passage.questions.map((question) => withPassage(passage, question)),
);

function seededRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state += 0x6d2b79f5;
    let value = Math.imul(state ^ (state >>> 15), state | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}
function shuffle<T>(items: readonly T[], random: () => number): T[] {
  const result = [...items];
  for (let index = result.length - 1; index > 0; index--) {
    const other = Math.floor(random() * (index + 1));
    [result[index], result[other]] = [result[other], result[index]];
  }
  return result;
}

/** Passage index is zero-based and wraps at 26; count is clamped to 0..8. */
export function getReadingQuestions(
  passageIndex: number,
  count = 8,
  seed = 1,
): ReadingQuestion[] {
  const index = Number.isFinite(passageIndex) ? Math.trunc(passageIndex) : 0;
  const passage =
    readingPassages[
      ((index % readingPassages.length) + readingPassages.length) %
        readingPassages.length
    ];
  const requested = Number.isFinite(count)
    ? Math.min(8, Math.max(0, Math.floor(count)))
    : 8;
  const random = seededRandom(Number.isFinite(seed) ? seed : 1);
  return shuffle(passage.questions, random)
    .slice(0, requested)
    .map((question) => {
      const correct = question.choices[question.answer];
      const choices = shuffle(question.choices, random);
      return {
        ...withPassage(passage, question),
        choices,
        answer: choices.indexOf(correct),
      };
    });
}
